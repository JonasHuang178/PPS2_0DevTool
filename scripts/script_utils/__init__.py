"""共用模組層。

分組依**技術領域**，不依應用功能：

    logger.py        所有共用模組與入口腳本共用的 log（唯一設定 logging 的地方）
    system_utils.py  系統層面：檔案系統、暫存目錄、環境變數、路徑表示法
    gitlab_utils.py  GitLab REST（尚無內容）

依功能分組會讓第二個功能需要同一個能力時無處可放。只服務單一功能的邏輯不
屬於這裡，應該留在 scripts/<功能>/ 之下。

一個分組**預設是單一 .py 檔案**。出現下列任一情況才拆成目錄：

    1. 單檔超過約 500 行，翻閱開始有負擔
    2. 分組內出現彼此不相依的獨立關切（例如 GitLab 的 REST client，與一個
       完全不經過 client 的 webhook 簽章驗證）

拆的時候由該目錄的 __init__.py 原樣 re-export。呼叫端一律寫
`from script_utils import <分組>`，兩種形式在 import 端完全相同，因此拆與不拆
都不需要更動任何一行呼叫。

反過來說，分組還小的時候就先拆成目錄，換到的只有一份要跟著維護的再匯出清單
—— 漏掉一筆的症狀是「函式明明寫好了卻搆不到」。預設單檔，是因為這個決定晚做
比早做便宜：真的長大了再拆，成本是一次搬移，零個呼叫端改動。

共用模組的規則（見 openspec/specs/script-envelope）：
    不印任何東西到 stdout —— stdout 是結果通道
    不結束行程，錯誤以例外拋出，是否結束由入口腳本決定
    不自行讀取設定檔或環境變數，所需的值由呼叫端明著傳入
    回傳資料結構，不回傳 JSON 字串
"""
